/* ── Trace builders ──────────────────────────────────────────────────────── */

/* Convert 6-digit hex colour to rgba() string with the given alpha (0–1).   */
/* Plotly requires rgba() or 6-digit hex; 8-digit hex (#RRGGBBAA) is not      */
/* reliably parsed by the tinycolor2 bundled in Plotly 2.26.2.                */
function hexToRgba(hex, alpha) {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return "rgba(" + r + "," + g + "," + b + "," + alpha + ")";
}

/* Take every nth element from an array — used to downsample the CI ribbon    */
/* polygon so Plotly can fill it reliably on large multi-year records.         */
function downsample(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr[i]);
  return out;
}

/* Shaded ribbon for SSEM 95% CI — low opacity fill, no legend entry.         */
/* xRibbon: x coords for the fill polygon (may be coarser than xMed).         */
/* xMed:    x coords for the median line (full resolution).                   */
function ribbon(xRibbon, xMed, med, lo, hi, name, col) {
  return [
    {x: xRibbon.concat(xRibbon.slice().reverse()),
     y: hi.concat(lo.slice().reverse()),
     fill:"toself", fillcolor:hexToRgba(col, 0.16), line:{width:0},
     type:"scatter", mode:"lines", showlegend:false, hoverinfo:"skip", name:name+" CI"},
    {x: xMed, y:med, type:"scatter", mode:"lines",
     line:{color:col, width:LW.ssem_med}, name:name}
  ];
}

/* Solid line with explicit width and optional dash style */
function line_trace(x, y, col, name, dash, width) {
  return {x, y, type:"scatter", mode:"lines",
    line:{color:col, width:width||1.5, dash:dash||"solid"}, name};
}

/* Line + markers for data with discrete year points */
function lm_trace(x, y, col, name, dash, width) {
  return {x, y, type:"scatter", mode:"lines+markers",
    line:{color:col, width:width||LW.cmip6, dash:dash||"solid"}, marker:{size:4}, name};
}

/* ── Main trace builder ──────────────────────────────────────────────────── */
function getTraces() {
  const d  = DATA[site];
  const vc = VARS[vari];
  const f  = vc.field;
  const t  = [];

  /* ── Sub-daily (2008 representative year) ────────────────────────────── */
  if (ts === "subdaily") {
    /* SSEM median line (US-NR1 and US-MMS only; d.ssem is null for other sites) */
    const sd = d.ssem ? d.ssem.subdaily : null;
    if (sd && vc.streams.includes("ssem") && f && cb("cb_ssem_med") && sd[f])
      t.push(line_trace(sd.dates, sd[f], C.ssem, "SSEM 2008", "solid", LW.ssem_med));

    /* FLUXNET sub-daily 2008 — scatter, coloured by NEE QC flag (0-3) */
    if (cb("cb_fluxnet_sd") && d.fluxnet_sd) {
      const fsd = d.fluxnet_sd;
      /* QC colour key: 0=measured (black), 1=high-quality gap-fill (green),
         2=medium-quality (orange), 3=low-quality (red) */
      const QC_COL  = ["#000000", "#27ae60", "#e67e22", "#c0392b"];
      const QC_LABL = [
        "FLUXNET QC=0 (measured)",
        "FLUXNET QC=1 (gap-filled, high quality)",
        "FLUXNET QC=2 (gap-filled, medium quality)",
        "FLUXNET QC=3 (gap-filled, low quality)"
      ];
      if (vari === "NEE" && fsd.nee) {
        /* One trace per QC level so Plotly assigns a distinct legend entry */
        [0,1,2,3].forEach(q => {
          const idx = [];
          fsd.nee_qc.forEach((v,i) => { if (v === q) idx.push(i); });
          if (idx.length > 0)
            t.push({
              x: idx.map(i => fsd.dates[i]),
              y: idx.map(i => fsd.nee[i]),
              type:"scatter", mode:"markers",
              marker:{color:QC_COL[q], size:2, opacity:0.7},
              name:QC_LABL[q], showlegend:true
            });
        });
      }
      if (vari === "Energy") {
        /* Show SW, LE, H as lines; no QC colouring for energy */
        [["sw",C.sw,"SW_IN"],["le",C.le,"LE"],["h",C.h_,"H"]].forEach(([fld,col,nm]) => {
          if (fsd[fld]) t.push(line_trace(fsd.dates, fsd[fld], col, "FLUXNET "+nm, "solid", LW.fluxnet));
        });
      }
      if (vari === "ET" && fsd.et)
        t.push(line_trace(fsd.dates, fsd.et, C.fluxnet, "FLUXNET ET", "solid", LW.fluxnet));
    }
    return t;
  }

  /* ── Daily (full record) ─────────────────────────────────────────────── */
  if (ts === "daily") {
    /* d.ssem is null for sites without an SSEM run (DE-Tha, DK-Sor) */
    const dd = d.ssem ? d.ssem.daily : null;
    const fd = d.fluxnet.daily;

    /* SSEM ribbon / median line */
    if (dd && vc.streams.includes("ssem") && f && dd[f+"_med"]) {
      if (cb("cb_ssem_ci")) {
        /* Downsample CI ribbon to weekly (every 7th day) — reduces the closed */
        /* polygon from ~18,992 to ~2,714 points so Plotly fills it reliably.  */
        /* The median line stays at full daily resolution.                      */
        const step = 7;
        t.push(...ribbon(
          downsample(dd.dates, step), dd.dates, dd[f+"_med"],
          downsample(dd[f+"_lo"], step), downsample(dd[f+"_hi"], step),
          "SSEM", C.ssem));
      }
      else if (cb("cb_ssem_med"))
        t.push(line_trace(dd.dates, dd[f+"_med"], C.ssem, "SSEM", "solid", LW.ssem_med));
    }

    /* FLUXNET daily as thick line (lw=3), QC stored separately but not coloured */
    if (vc.streams.includes("fluxnet") && cb("cb_fluxnet")) {
      if (f && fd[f] && vari !== "Energy")
        t.push(line_trace(fd.dates, fd[f], C.fluxnet, "FLUXNET", "solid", LW.fluxnet));
      if (vari === "Energy") {
        [["sw",C.sw],["lw",C.lw],["le",C.le],["h",C.h_]].forEach(([fld,col]) => {
          if (fd[fld]) t.push(line_trace(fd.dates, fd[fld], col, fld.toUpperCase(), "solid", LW.fluxnet));
        });
      }
      if (vari === "ET" && fd.et)
        t.push(line_trace(fd.dates, fd.et, C.fluxnet, "FLUXNET ET", "solid", LW.fluxnet));
    }
    return t;
  }

  /* ── Monthly (full record) ───────────────────────────────────────────── */
  if (ts === "monthly") {
    /* d.ssem is null for sites without SSEM; guard before accessing .monthly */
    const sm  = d.ssem ? d.ssem.monthly : null;
    const fm  = d.fluxnet.monthly;
    const fc  = d.fluxcom.monthly;
    const cms = d.cmip6;

    if (sm && vc.streams.includes("ssem") && f && sm[f] && cb("cb_ssem_med"))
      t.push(line_trace(sm.dates, sm[f], C.ssem, "SSEM", "solid", LW.ssem_med));

    if (vc.streams.includes("fluxnet") && f && fm[f] && cb("cb_fluxnet") && vari!=="Energy")
      t.push(line_trace(fm.dates, fm[f], C.fluxnet, "FLUXNET", "solid", LW.fluxnet));

    if (vc.streams.includes("fluxcom") && f && fc[f] && cb("cb_fluxcom"))
      t.push(line_trace(fc.dates, fc[f], C.fluxcom, "FLUXCOM 2001-2021", "dash", LW.fluxcom));

    [["CESM2","cb_cesm2",C.cesm2],
     ["IPSL-CM6A-LR","cb_ipsl",C.ipsl],
     ["UKESM1-0-LL","cb_ukesm",C.ukesm]]
      .forEach(([m,cbid,col]) => {
        if (!cb(cbid) || !vc.streams.includes("cmip6")) return;
        const md = cms[m].monthly;
        const y  = vari==="Energy" ? md.le : (f ? md[f] : null);
        if (y) t.push(line_trace(md.dates, y, col, m, "dot", LW.cmip6));
        if (vari==="Energy" && md.h && cb(cbid))
          t.push(line_trace(md.dates, md.h, col+"99", m+" H", "dashdot", LW.cmip6));
      });

    return t;
  }

  /* ── Annual (full record) — lines throughout, no bar charts ─────────── */
  if (ts === "annual") {
    const fa  = d.fluxcom.annual;
    const cms = d.cmip6;

    /* SSEM annual: US-NR1 and US-MMS only; d.ssem.annual absent for other sites */
    if (d.ssem && d.ssem.annual && vc.streams.includes("ssem") && f && cb("cb_ssem_med")) {
      const ann = d.ssem.annual;
      const yv  = f==="lai" ? ann.lai_avg : (f ? ann[f] : null);
      if (yv) t.push(lm_trace(ann.year.map(String), yv, C.ssem, "SSEM", "solid", LW.ssem_med));
    }

    /* FLUXNET annual: thick line+markers */
    if (vc.streams.includes("fluxnet") && cb("cb_fluxnet") && f) {
      const ann_fn = d.fluxnet.annual;
      const yv = ann_fn[f];
      if (yv) t.push(lm_trace(ann_fn.year.map(String), yv, C.fluxnet, "FLUXNET", "solid", LW.fluxnet));
    }

    /* FLUXCOM annual: dashed medium line */
    if (vc.streams.includes("fluxcom") && f && fa.year && cb("cb_fluxcom")) {
      const yv = f==="lai" ? null : fa[f];
      if (yv) t.push(line_trace(fa.year.map(String), yv, C.fluxcom, "FLUXCOM", "dash", LW.fluxcom));
    }

    /* CMIP6 annual: thin lines per model */
    [["CESM2","cb_cesm2",C.cesm2],
     ["IPSL-CM6A-LR","cb_ipsl",C.ipsl],
     ["UKESM1-0-LL","cb_ukesm",C.ukesm]]
      .forEach(([m,cbid,col]) => {
        if (!cb(cbid) || !vc.streams.includes("cmip6")) return;
        const ann = cms[m].annual;
        const yv  = f==="lai" ? ann.lai_avg : (f ? ann[f] : null);
        if (yv) t.push(line_trace(ann.year.map(String), yv, col, m, "dot", LW.cmip6));
      });
  }

  return t;
}

