# ─── Sub-daily display from 2008 single-year RDS ─────────────────────────────
# The 2008 RDS files are plain arrays (not lists) generated by Exercise 01.
# We use them only for the sub-daily timescale view (2008 representative year).
proc_ssem_subdaily_2008 <- function(rds_path, steps_per_day, run_year = 2008L) {
  cat(sprintf("  SSEM sub-daily 2008 [spd=%d] %s...\n",
              steps_per_day, basename(rds_path)))
  arr    <- readRDS(rds_path)                              # plain array
  step_s <- (24L * 60L / steps_per_day) * 60L
  n_use  <- dim(arr)[1]

  # Thin the sub-daily series to every 4th timestep to reduce JSON size:
  #   US-NR1 (48/day): every 4th → 12 points/day (2-hourly equivalent)
  #   US-MMS (24/day): every 4th →  6 points/day (4-hourly equivalent)
  si  <- seq(1L, n_use, 4L)
  dt0 <- as.POSIXct(sprintf("%d-01-01 00:00:00", run_year), tz = "UTC")
  sdt <- format(dt0 + (si - 1L) * step_s, "%Y-%m-%dT%H:%M", tz = "UTC")

  # Instantaneous median across ensemble members (not daily-integrated)
  sd_med <- function(vi, negate = FALSE) {
    raw <- arr[si, , vi]
    rnd(apply(raw, 1, median, na.rm = TRUE) * (if (negate) -1 else 1), 3)
  }

  list(
    dates = sdt,
    gpp   = sd_med(I_GPP),
    nee   = sd_med(I_NEP, negate = TRUE),
    rh    = sd_med(I_RH),
    lai   = rnd(apply(arr[si, , I_LAI], 1, median, na.rm = TRUE), 3)
  )
}


# ─── Daily / monthly / annual from full-record RDS ───────────────────────────
# The full-record RDS is a list produced by exercises/run_full_record.R.
# It contains a 3-D array [total_timesteps × ne × 12] plus metadata.
proc_ssem_full <- function(rds_path, site_id) {
  cat(sprintf("  SSEM full-record [%s] %s...\n", site_id, basename(rds_path)))
  meta          <- readRDS(rds_path)
  arr           <- meta$output
  years_present <- meta$years
  spd           <- meta$steps_per_day      # steps per day
  step_s        <- (24L * 60L / spd) * 60L

  # ── Build the day-level date sequence for the full record ───────────────
  # Each year contributes n_days × steps_per_day timesteps.
  # We regenerate the date vector from the year metadata so there is no
  # possibility of drift from the actual data timestamps.
  all_dates_d <- character(0)
  for (yr in years_present) {
    n_days      <- if (leap_year(yr)) 366L else 365L
    all_dates_d <- c(all_dates_d,
                     format(seq.Date(as.Date(sprintf("%d-01-01", yr)),
                                     by = "day", length.out = n_days)))
  }

  # ── Aggregate to daily ──────────────────────────────────────────────────
  dd <- agg_to_daily(arr, spd, step_s)

  # ── Trim to 2000-2025 ───────────────────────────────────────────────────
  # The first two SSEM years (1998-1999) serve as carbon pool spin-up.
  # Removing them keeps the displayed record within the 2000-2025 window
  # used consistently across all data sources in this dashboard.
  keep        <- all_dates_d >= "2000-01-01" & all_dates_d <= "2025-12-31"
  all_dates_d <- all_dates_d[keep]
  trim_ci <- function(ci) list(lo = ci$lo[keep], med = ci$med[keep], hi = ci$hi[keep])
  dd$gpp  <- trim_ci(dd$gpp)
  dd$nee  <- trim_ci(dd$nee)
  dd$rh   <- trim_ci(dd$rh)
  dd$ra   <- trim_ci(dd$ra)
  dd$lai  <- trim_ci(dd$lai)

  # ── Monthly aggregation: average daily values within each year-month ────
  # 'ym' is a character vector like "1998-01", "1998-01", ..., "2023-12"
  # One value per calendar day.
  ym       <- substr(all_dates_d, 1, 7)
  ym_uniq  <- unique(ym)
  dates_m  <- paste0(ym_uniq, "-01")

  mo_mean  <- function(v) rnd(vapply(ym_uniq, function(m) mean(v[ym == m], na.rm = TRUE), numeric(1)))

  # ── Annual aggregation: sum of daily gC m-2 d-1 = gC m-2 yr-1 ──────────
  yr_str   <- substr(all_dates_d, 1, 4)
  yr_uniq  <- unique(yr_str)

  ann_sum  <- function(v) rnd(vapply(yr_uniq, function(y) sum( v[yr_str == y], na.rm = TRUE), numeric(1)), 1)
  ann_mean <- function(v) rnd(vapply(yr_uniq, function(y) mean(v[yr_str == y], na.rm = TRUE), numeric(1)), 3)

  list(
    daily = list(
      dates   = all_dates_d,
      gpp_med = dd$gpp$med, gpp_lo = dd$gpp$lo, gpp_hi = dd$gpp$hi,
      nee_med = dd$nee$med, nee_lo = dd$nee$lo, nee_hi = dd$nee$hi,
      rh_med  = dd$rh$med,  rh_lo  = dd$rh$lo,  rh_hi  = dd$rh$hi,
      lai_med = dd$lai$med, lai_lo = dd$lai$lo,  lai_hi = dd$lai$hi
    ),
    monthly = list(
      dates = dates_m,
      gpp   = mo_mean(dd$gpp$med),
      nee   = mo_mean(dd$nee$med),
      rh    = mo_mean(dd$rh$med),
      lai   = mo_mean(dd$lai$med)
    ),
    annual = list(
      year    = as.integer(yr_uniq),
      gpp     = ann_sum(dd$gpp$med),
      nee     = ann_sum(dd$nee$med),
      rh      = ann_sum(dd$rh$med),
      lai_avg = ann_mean(dd$lai$med)
    )
  )
}


# =============================================================================
# FLUXNET daily processor — full record (all available years)
# =============================================================================

proc_fluxnet <- function(csv_path, site_id) {
  cat(sprintf("  FLUXNET full-record [%s] %s...\n", site_id, basename(csv_path)))
  is_nr1   <- site_id == "US-NR1"
  nee_col  <- if (is_nr1) "NEE_CUT_REF"     else "NEE_VUT_REF"
  nee_qc   <- if (is_nr1) "NEE_CUT_REF_QC"  else "NEE_VUT_REF_QC"
  gpp_col  <- if (is_nr1) "GPP_NT_CUT_REF"  else "GPP_NT_VUT_REF"
  reco_col <- if (is_nr1) "RECO_NT_CUT_REF" else "RECO_NT_VUT_REF"

  df <- read_csv(csv_path, show_col_types = FALSE) |>
    mutate(across(where(is.numeric), ~ replace(., . == -9999, NA))) |>
    mutate(date = as.Date(as.character(DATE))) |>
    # Limit to 2000-2025 to match the global date range of the dashboard
    filter(date >= as.Date("2000-01-01"), date <= as.Date("2025-12-31"))

  # Carbon fluxes: μmol m-2 s-1 × 86400 s/d × 12.011e-6 g/μmol = gC m-2 d-1
  C    <- UMOL_TO_GC_PER_S * 86400
  nee  <- rnd(df[[nee_col]]  * C)
  gpp  <- rnd(df[[gpp_col]]  * C)
  reco <- rnd(df[[reco_col]] * C)
  qc   <- df[[nee_qc]]

  # Energy (W m-2) and ET from LE (mm d-1)
  le <- rnd(df[["LE_F_MDS"]], 2)
  h  <- rnd(df[["H_F_MDS"]],  2)
  sw <- rnd(df[["SW_IN_F"]],  2)
  lw <- rnd(df[["LW_IN_F"]],  2)
  ta <- rnd(df[["TA_F"]],     2)
  et <- rnd(df[["LE_F_MDS"]] * LE_TO_MM_DAY, 3)

  dates_d <- format(df$date)

  # Monthly: average daily values within each year-month
  ym      <- substr(dates_d, 1, 7)
  ym_uniq <- unique(ym)
  dates_m <- paste0(ym_uniq, "-01")
  mm      <- function(v) rnd(vapply(ym_uniq, function(m) mean(v[ym == m], na.rm = TRUE), numeric(1)))

  # Annual: sum of daily gC m-2 d-1 = gC m-2 yr-1
  yr_str  <- substr(dates_d, 1, 4)
  yr_uniq <- unique(yr_str)
  ann_sum <- function(v) rnd(vapply(yr_uniq, function(y) sum(v[yr_str == y], na.rm = TRUE), numeric(1)), 1)

  list(
    daily = list(
      dates  = dates_d,
      nee    = nee, gpp = gpp, reco = reco, nee_qc = as.integer(qc),
      le = le, h = h, sw = sw, lw = lw, et = et, ta = ta
    ),
    monthly = list(
      dates = dates_m,
      nee   = mm(nee), gpp = mm(gpp), reco = mm(reco),
      le = mm(le), h = mm(h), et = mm(et)
    ),
    annual = list(
      year = as.integer(yr_uniq),
      gpp  = ann_sum(gpp),
      nee  = ann_sum(nee)
    )
  )
}


# =============================================================================
# FLUXCOM monthly processor (unchanged — 2001–2021)
# =============================================================================

proc_fluxcom <- function(csv_path) {
  cat(sprintf("  FLUXCOM %s...\n", basename(csv_path)))
  df <- read.csv(csv_path, comment.char = "#") |>
    mutate(date  = as.Date(paste(year, month, "01", sep = "-")),
           days  = days_in_month(date))

  # Annual: sum(gC m-2 d-1 × days) = gC m-2 yr-1
  ann <- df |>
    group_by(year) |>
    summarise(gpp = rnd(sum(GPP_gC_m2_d * days, na.rm = TRUE), 1),
              nee = rnd(sum(NEE_gC_m2_d * days, na.rm = TRUE), 1),
              .groups = "drop")

  list(
    monthly = list(
      dates = format(df$date),
      gpp   = rnd(df$GPP_gC_m2_d),
      nee   = rnd(df$NEE_gC_m2_d),
      et    = rnd(df$ET_mm_d),
      ter   = rnd(df$TER_gC_m2_d)
    ),
    annual = list(year = ann$year, gpp = ann$gpp, nee = ann$nee)
  )
}


# =============================================================================
# CMIP6 monthly processor (unchanged — 1980–2021)
# =============================================================================

proc_cmip6 <- function(csv_path, model_name) {
  cat(sprintf("  CMIP6 [%s] %s...\n", model_name, basename(csv_path)))
  df <- read_csv(csv_path, show_col_types = FALSE) |>
    # Trim CMIP6 to 2000-2021; pre-2000 historical data is outside the dashboard window
    filter(year >= 2000L) |>
    mutate(
      date = as.Date(paste(year, month, "01", sep = "-")),
      days = days_in_month(date),
      gpp  = rnd(gpp_kgC_m2_s  * KGC_S_TO_GC_DAY),
      rh   = rnd(rh_kgC_m2_s   * KGC_S_TO_GC_DAY),
      ra   = rnd(ra_kgC_m2_s   * KGC_S_TO_GC_DAY),
      # NEE = Ra + Rh - GPP (positive = net emission; approximation from model outputs)
      nee  = rnd((ra_kgC_m2_s + rh_kgC_m2_s - gpp_kgC_m2_s) * KGC_S_TO_GC_DAY),
      lai  = rnd(lai_m2_m2, 3),
      le   = rnd(latent_heat_W_m2,   2),
      h    = rnd(sensible_heat_W_m2, 2),
      sw   = rnd(sw_down_sfc_W_m2,   2),
      et   = rnd(latent_heat_W_m2 * LE_TO_MM_DAY, 3)
    )

  scen <- df$scenario[1]

  ann <- df |>
    group_by(year) |>
    summarise(
      gpp     = rnd(sum(gpp * days, na.rm = TRUE), 1),
      nee     = rnd(sum(nee * days, na.rm = TRUE), 1),
      rh      = rnd(sum(rh  * days, na.rm = TRUE), 1),
      lai_avg = rnd(mean(lai, na.rm = TRUE), 3),
      .groups = "drop"
    )

  list(
    scenario = scen,
    monthly  = list(
      dates = format(df$date),
      gpp   = df$gpp, nee = df$nee, rh = df$rh,
      lai   = df$lai, le  = df$le,  h  = df$h,
      sw    = df$sw,  et  = df$et
    ),
    annual = list(year = ann$year, gpp = ann$gpp, nee = ann$nee,
                  rh = ann$rh, lai_avg = ann$lai_avg)
  )
}


# =============================================================================
# FLUXNET sub-daily processor — 2008 only, all four sites
# =============================================================================
# Loads 2008 half-hourly (or hourly for US-MMS) NEE and met observations.
# QC flag is retained so the dashboard can colour-code points by data quality.
# Only the needed columns are read to keep memory use manageable — HH files
# are 600-700 MB but col_select lets readr skip unwanted columns.
#
# Returns NULL if no data is found for the requested year.

proc_fluxnet_subdaily <- function(csv_path, site_id, year = 2008L) {
  cat(sprintf("  FLUXNET sub-daily %d [%s] %s...\n", year, site_id, basename(csv_path)))
  is_nr1  <- site_id == "US-NR1"
  is_mms  <- site_id == "US-MMS"
  nee_col <- if (is_nr1) "NEE_CUT_REF"    else "NEE_VUT_REF"
  nee_qc  <- if (is_nr1) "NEE_CUT_REF_QC" else "NEE_VUT_REF_QC"
  ts_col  <- if (is_mms) "TIMESTAMP_START" else "DATETIME_START"

  # Read only the 7 needed columns; avoids loading the full 200-column HH file
  df <- read_csv(csv_path, show_col_types = FALSE,
                 col_select = any_of(c(ts_col, nee_col, nee_qc,
                                       "SW_IN_F", "TA_F", "LE_F_MDS", "H_F_MDS"))) |>
    mutate(across(where(is.numeric), ~ replace(., . == -9999, NA)))

  # Parse timestamp to POSIXct — two formats depending on site
  if (is_mms) {
    # US-MMS HR: TIMESTAMP_START is an integer YYYYMMDDHHMM (e.g. 200801010000)
    df <- df |>
      mutate(dt = as.POSIXct(strptime(as.character(.data[[ts_col]]),
                                       "%Y%m%d%H%M", tz = "UTC")))
  } else {
    # HH sites (US-NR1, DE-Tha, DK-Sor): DATETIME_START is ISO 8601 with Z suffix;
    # readr already parses it as POSIXct so we just rename the column
    df <- df |> mutate(dt = .data[[ts_col]])
  }

  # Filter to the target year
  df <- df |> filter(year(dt) == year)

  if (nrow(df) == 0L) {
    warning(sprintf("proc_fluxnet_subdaily: no data for %d in %s", year, basename(csv_path)))
    return(NULL)
  }

  # Thin to every 4th timestep — consistent with SSEM sub-daily thinning:
  #   HH sites (48 steps/day): every 4th -> 12 points/day (2-hourly equivalent)
  #   HR sites (24 steps/day): every 4th ->  6 points/day (4-hourly equivalent)
  si <- seq(1L, nrow(df), 4L)
  df <- df[si, ]

  list(
    dates  = format(df$dt, "%Y-%m-%dT%H:%M", tz = "UTC"),
    nee    = rnd(df[[nee_col]], 3),
    nee_qc = as.integer(df[[nee_qc]]),
    sw     = rnd(df$SW_IN_F,  2),
    ta     = rnd(df$TA_F,     2),
    le     = rnd(df$LE_F_MDS, 2),
    h      = rnd(df$H_F_MDS,  2),
    et     = rnd(df$LE_F_MDS * LE_TO_MM_DAY, 3)
  )
}


